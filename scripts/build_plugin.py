#!/usr/bin/env python3
"""Reproducible public Hatchable artifacts and portable plugin ZIP; no deploy side effects."""
import argparse
import hashlib
import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PUBLIC_FILES = ['api/chatgpt-mcp.js','lib/contract.js','lib/core.js','lib/data.js','lib/runtime.js','lib/schema.js','lib/site-config.js','pages/health.js']

def digest(data):
    return hashlib.sha256(data).hexdigest()

def build(check=False, output=None):
    result = {}
    widget = (ROOT/'python/assets/app-v1.html').read_text()
    chunks = [widget[i:i+8000] for i in range(0,len(widget),8000)]
    result['hatchable/lib/widget.js'] = ('// Generated from python/assets/app-v1.html; do not edit.\nconst parts = '+json.dumps(chunks,ensure_ascii=False)+';\nexport default parts.join("");\n').encode()
    source_paths = ['python/assets/app-v1.html', 'scripts/build_plugin.py', 'scripts/bundle_public_mcp.mjs'] + ['hatchable/'+x for x in PUBLIC_FILES] + [str(p.relative_to(ROOT)) for p in sorted((ROOT/'hatchable/lib').glob('data-part*.js'))]
    source_hashes = {p:digest((ROOT/p).read_bytes()) for p in source_paths}
    source_digest = digest(json.dumps(source_hashes,sort_keys=True,separators=(',',':')).encode())
    release = {'version':'1.1.0','profile':'public-readonly-native-images','source_sha256':source_digest,'widget_sha256':digest(widget.encode()),'tool_count':9}
    result['hatchable/lib/release.js'] = ('// Generated by scripts/build_plugin.py.\nexport const RELEASE = '+json.dumps(release,separators=(',',':'))+';\n').encode()
    for rel in PUBLIC_FILES+['lib/widget.js','lib/release.js']:
        raw = result.get('hatchable/'+rel) or (ROOT/'hatchable'/rel).read_bytes()
        text = raw.decode()
        if rel == 'lib/core.js':
            # The experimental renderer stays in source and Python tests, never in the public isolate.
            start=text.index('const RENDER_JOBS =')
            end=text.index('function validateImageInput(',start)
            text=text[:start]+text[end:]
            text=re.sub(r'^import .* from "(?:node:crypto|\./site-config.js)";\n','',text,flags=re.M)
            text=text.replace('import { generationHandoff, requireRendering }','import { generationHandoff }')
            text=text.replace('  const { browser } = await import("hatchable");\n','')
            text='import { browser } from "hatchable";\n'+text
            text='\n'.join(line for line in text.split('\n') if not any("if(name==='"+name+"')" in line for name in ['render_brand_direction','run_brand_workflow','get_render_job']))
        text=re.sub(r'([\'"])(?:\.\./lib/|\./)([^\'"]+)([\'"])',lambda m:m[1]+'lib/'+m[2]+m[3],text)
        result['deployment/hatchable/'+rel] = text.encode()
    manifest={'release':release,'sources':source_hashes,'files':{p.removeprefix('deployment/hatchable/'):digest(b) for p,b in result.items() if p.startswith('deployment/hatchable/')}}
    result['deployment/hatchable/manifest.json']=(json.dumps(manifest,indent=2)+'\n').encode()
    for path,data in result.items():
        target=ROOT/path
        if check:
            if not target.is_file() or target.read_bytes()!=data:raise SystemExit('STALE: '+path)
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
    if output:
        output=Path(output);output.mkdir(parents=True,exist_ok=True)
        package=ROOT/'plugins/infographic-artist';archive=output/'infographic-artist-1.1.0.zip'
        with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
            for path in sorted(package.rglob('*')):
                if not path.is_file():continue
                rel=path.relative_to(package)
                if path.is_symlink() or any(x in rel.parts for x in ['.git','node_modules','__pycache__']):raise SystemExit('Unsafe package file: '+str(rel))
                if path.suffix.lower() in {'.woff','.woff2','.ttf','.otf','.env'}:raise SystemExit('Forbidden package file: '+str(rel))
                info=zipfile.ZipInfo(str(rel),(2026,10,19,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o644<<16;z.writestr(info,path.read_bytes())
        (output/(archive.name+'.sha256')).write_text(digest(archive.read_bytes())+'  '+archive.name+'\n')
        print('PACKAGE',archive,archive.stat().st_size)
    print(json.dumps(release,indent=2))

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--output');args=parser.parse_args();build(args.check,args.output)
